// Helper to assemble minimal valid Game Boy DMG homebrew
function createMinimalGameBoyHomebrew(): Uint8Array {
  const gb = new Uint8Array(32768); // 32KB Game Boy ROM

  // Entry point at 0x0100: NOP; JP 0x0150
  gb[0x100] = 0x00; // NOP
  gb[0x101] = 0xc3; // JP 0x0150
  gb[0x102] = 0x50;
  gb[0x103] = 0x01;

  // Nintendo Logo at 0x0104 - 0x0133
  const logo = [
    0xce, 0xed, 0x66, 0x66, 0xcc, 0x0d, 0x00, 0x0b, 0x03, 0x73, 0x00, 0x83,
    0x00, 0x0c, 0x00, 0x0d, 0x00, 0x08, 0x11, 0x1f, 0x88, 0x89, 0x00, 0x0e,
    0xdc, 0xcc, 0x6e, 0xe6, 0xdd, 0xdd, 0xd9, 0x99, 0xbb, 0xbb, 0x67, 0x63,
    0x6e, 0x0e, 0xec, 0xcc, 0xdd, 0xdc, 0x99, 0x9f, 0xbb, 0xb9, 0x33, 0x3e,
  ];
  for (let i = 0; i < logo.length; i++) gb[0x104 + i] = logo[i];

  // Title: "TOBU TOBU GB" (16 bytes 0x0134-0x0143)
  const title = 'TOBUTOBU GB';
  for (let i = 0; i < title.length; i++) gb[0x134 + i] = title.charCodeAt(i);

  gb[0x147] = 0x00; // ROM ONLY
  gb[0x148] = 0x00; // 32KB
  gb[0x149] = 0x00; // RAM 0
  gb[0x14a] = 0x01; // Non-Japan

  // Calculate Header Checksum at 0x014D
  let x = 0;
  for (let i = 0x134; i <= 0x14c; i++) {
    x = x - gb[i] - 1;
  }
  gb[0x14d] = x & 0xff;

  // Program code at 0x0150
  let p = 0x150;
  // DI (disable interrupts)
  gb[p++] = 0xf3;
  // LD SP, $FFFE
  gb[p++] = 0x31; gb[p++] = 0xfe; gb[p++] = 0xff;
  // Set BGP = $E4 (Dark green / light green)
  gb[p++] = 0x3e; gb[p++] = 0xe4; // LD A, $E4
  gb[p++] = 0xe0; gb[p++] = 0x47; // LDH ($47), A
  // Set LCDC = $91 (LCD On, BG on, Tile map $9800)
  gb[p++] = 0x3e; gb[p++] = 0x91;
  gb[p++] = 0xe0; gb[p++] = 0x40;

  // Main game loop (JR -2)
  const loop = p;
  gb[p++] = 0x18; gb[p++] = 0xfe; // JR -2

  return gb;
}

