// Helper to assemble minimal valid iNES 1.0 test ROM (16KB PRG, 8KB CHR)
function createMinimalNesHomebrew(title: string): Uint8Array {
  // iNES header: 16 bytes
  const header = new Uint8Array([
    0x4e, 0x45, 0x53, 0x1a, // "NES\x1A"
    0x01,                   // 1 x 16KB PRG ROM
    0x01,                   // 1 x 8KB CHR ROM
    0x00,                   // Mapper 0, horizontal mirroring
    0x00,                   // Mapper 0
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  ]);

  const prgRom = new Uint8Array(16384);
  const chrRom = new Uint8Array(8192);

  // Fill CHR-ROM with a basic font / tile patterns
  // Tile 1: Block pattern
  for (let i = 0; i < 8; i++) {
    chrRom[16 + i] = 0xff;
    chrRom[16 + i + 8] = 0x00;
  }

  // 6502 code at PRG start ($C000 / $8000)
  let p = 0;
  // SEI
  prgRom[p++] = 0x78;
  // CLD
  prgRom[p++] = 0xd8;
  // LDX #$FF; TXS
  prgRom[p++] = 0xa2; prgRom[p++] = 0xff;
  prgRom[p++] = 0x9a;
  // Wait VBlank
  // LDA $2002; BPL loop
  const loopAddr = p;
  prgRom[p++] = 0xad; prgRom[p++] = 0x02; prgRom[p++] = 0x20;
  prgRom[p++] = 0x10; prgRom[p++] = 0xfb; // -5

  // Set PPU palette ($3F00)
  prgRom[p++] = 0xad; prgRom[p++] = 0x02; prgRom[p++] = 0x20; // reset latch
  prgRom[p++] = 0xa9; prgRom[p++] = 0x3f;
  prgRom[p++] = 0x8d; prgRom[p++] = 0x06; prgRom[p++] = 0x20;
  prgRom[p++] = 0xa9; prgRom[p++] = 0x00;
  prgRom[p++] = 0x8d; prgRom[p++] = 0x06; prgRom[p++] = 0x20;

  // Background color = Dark Blue ($01)
  prgRom[p++] = 0xa9; prgRom[p++] = 0x01;
  prgRom[p++] = 0x8d; prgRom[p++] = 0x07; prgRom[p++] = 0x20;
  // Tile color 1 = White ($30)
  prgRom[p++] = 0xa9; prgRom[p++] = 0x30;
  prgRom[p++] = 0x8d; prgRom[p++] = 0x07; prgRom[p++] = 0x20;

  // Enable PPU Rendering ($2001 = $1e)
  prgRom[p++] = 0xa9; prgRom[p++] = 0x1e;
  prgRom[p++] = 0x8d; prgRom[p++] = 0x01; prgRom[p++] = 0x20;

  // Infinite main loop
  const mainLoop = p;
  prgRom[p++] = 0x4c; prgRom[p++] = mainLoop & 0xff; prgRom[p++] = (0xc000 + mainLoop) >> 8;

  // Vector Table at end of 16KB PRG ($FFF8-$FFFF)
  const nmiVector = 0xc000;
  const resetVector = 0xc000;
  const irqVector = 0xc000;

  prgRom[16384 - 6] = nmiVector & 0xff;
  prgRom[16384 - 5] = (nmiVector >> 8) & 0xff;
  prgRom[16384 - 4] = resetVector & 0xff;
  prgRom[16384 - 3] = (resetVector >> 8) & 0xff;
  prgRom[16384 - 2] = irqVector & 0xff;
  prgRom[16384 - 1] = (irqVector >> 8) & 0xff;

  // Combine header + PRG + CHR
  const total = new Uint8Array(16 + 16384 + 8192);
  total.set(header, 0);
  total.set(prgRom, 16);
  total.set(chrRom, 16 + 16384);
  return total;
}

